"""Writes docs/4K-ASSET-REPORT.md: every bundled broadcast asset, its own size, the largest size it is drawn at on a 4K
output (measured by scene_audit.py, /tmp/4k/scenes/report.json), and what it needs.
    python3 e2e-rig/4k/asset_report.py        (run scene_audit.py first)
"""
import json, os, subprocess
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BRAND = os.path.join(ROOT, 'public/brand/overdrive')
rep = json.load(open('/tmp/4k/scenes/report.json'))
drawn = {}   # asset path -> (max upscale at 4K, drawn size, scenes)
for row in rep:
    for x in row['raster']:
        src = x['src'].split('?')[0]
        if not src.startswith('/brand/overdrive/'): continue
        cur = drawn.get(src, (0, '', set()))
        best = (x['upscale'], x['drawn']) if x['upscale'] > cur[0] else (cur[0], cur[1])
        drawn[src] = (best[0], best[1], cur[2] | {row['route']})

# transient graphics (map card pop-up) measured by transient_sizes.py
if os.path.exists('/tmp/4k/scenes/extra.json'):
    for x in json.load(open('/tmp/4k/scenes/extra.json')):
        cur = drawn.get(x['src'], (0, '', set()))
        best = (x['upscale'], x['drawn']) if x['upscale'] > cur[0] else (cur[0], cur[1])
        drawn[x['src']] = (best[0], best[1], cur[2] | {x['scene']})
# all team logos are drawn by the same components: the largest measured team logo applies to every team file
team = max(((v[0], v[1]) for k, v in drawn.items() if '/teams/' in k), default=None)
TEAM_SCENES = set().union(*[v[2] for k, v in drawn.items() if '/teams/' in k]) if team else set()
mapc = max(((v[0], v[1]) for k, v in drawn.items() if '/maps/' in k), default=None)   # same for the 5 map photos
MAP_SCENES = set().union(*[v[2] for k, v in drawn.items() if '/maps/' in k]) if mapc else set()

def probe(p):
    ext = p.rsplit('.', 1)[-1].lower()
    if ext in ('webm', 'mp4'):
        j = json.loads(subprocess.run(['ffprobe', '-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=width,height,r_frame_rate:format=duration:stream_tags=alpha_mode', '-of', 'json', p], capture_output=True, text=True).stdout)
        s = j['streams'][0]; n, d = s['r_frame_rate'].split('/')
        return 'video', s['width'], s['height'], f"{round(int(n) / int(d))} fps, {float(j['format'].get('duration', 0)):.1f} s{', alpha' if s.get('tags', {}).get('alpha_mode') == '1' else ''}"
    if ext in ('png', 'jpg', 'jpeg', 'webp', 'gif'):
        w, h = Image.open(p).size; return 'raster', w, h, ''
    if ext == 'svg': return 'vector', 0, 0, ''
    return None

rows = []
for dp, _, fs in os.walk(BRAND):
    if '/4k' in dp: continue
    for f in sorted(fs):
        p = os.path.join(dp, f); rel = os.path.relpath(p, BRAND); url = f'/brand/overdrive/{rel}'
        info = probe(p)
        if not info: continue
        kind, w, h, extra = info
        up, size, scenes = drawn.get(url, (None, '', set()))
        if rel.startswith('teams/') and team and (up is None or up < team[0]): up, size, scenes = team[0], team[1], TEAM_SCENES
        if rel.startswith('maps/') and mapc and (up is None or up < mapc[0]): up, size, scenes = mapc[0], mapc[1], MAP_SCENES
        if url.endswith('bg-vote.jpg'): status, need = 'Not broadcast', 'Phone vote page only'
        elif kind == 'vector': status, need = 'Vector', 'Native at any size'
        elif kind == 'video':
            status = 'Video, 1080p source' if (w, h) == (1920, 1080) else 'Video'
            need = f'4K re-render 3840×2160 from the original project (same timing{", alpha" if "alpha" in extra else ""}{", 60 fps target" if extra.startswith("30") else ""})'
        elif up is None:
            status, need = 'Not used by the default event', 'Classic theme / unused variant: check if an event uses it (same 4K rule: ≥ 2× its on-air size)'
        elif up <= 1.05: status, need = 'OK at 4K', f'Drawn up to {size} px, has {w}×{h}'
        else:
            status = 'Low resolution at 4K'
            need = f'Drawn up to {size} px at 4K ({up}× its pixels): needs ≥ {round(w * up)}×{round(h * up)} or an SVG' if 'teams/' in rel or rel in ('logo.png', 'mark.png') else f'Drawn up to {size} px at 4K ({up}× its pixels): needs ≥ {round(w * up)}×{round(h * up)}'
        rows.append((rel, kind, f'{w}×{h}' if w else 'vector', extra, status, need, len(scenes)))

order = {'Low resolution at 4K': 0, 'Video, 1080p source': 1, 'Video': 1, 'Not used by the default event': 2, 'OK at 4K': 3, 'Vector': 4, 'Not broadcast': 5}
rows.sort(key=lambda r: (order.get(r[4], 9), r[0]))
low = [r for r in rows if r[4] in ('Low resolution at 4K', 'Video, 1080p source', 'Video')]
L = ['# 4K asset report', '',
     f'Every bundled broadcast asset in `public/brand/overdrive/` ({len(rows)} files), its own size, and the largest size it is drawn at on a 3840×2160 output, measured in all 30 scenes by `e2e-rig/4k/scene_audit.py`. Generated by `e2e-rig/4k/asset_report.py`.',
     '', f'**{len(low)} assets still limit 4K picture quality** (listed first). They are kept exactly as they are: nothing has been upscaled, replaced or described as 4K. To upgrade one, put the higher-resolution file in `public/brand/overdrive/4k/` under the same name (see the README there; an SVG may replace a PNG). 4K outputs then use it automatically, 1080p outputs keep the original.',
     '', 'Text, frames, bars, brackets, scoreboards, cards and the Wildcard map art are drawn in code and are already native 4K (not listed).', '',
     '| File | Type | Own size | Details | Status at 4K | What it needs | Scenes |', '| --- | --- | --- | --- | --- | --- | --- |']
for rel, kind, size, extra, status, need, n in rows:
    L.append(f'| `{rel}` | {kind} | {size} | {extra} | {"**" + status + "**" if status.startswith(("Low", "Video")) else status} | {need} | {n or ""} |')
L += ['', 'Assets that cannot be made native 4K in code, whatever is done: camera feeds (720p by default, 1080p optional per caster), game capture at its own resolution, uploaded media and images below 4K (the upload screens now say so, per role).',
      '', 'Sources needed from the design team (original project files): the 13 WebM loops/frames/stingers, the 6 title plates, the mark. Higher-resolution in-game captures: the 5 map photos. Team logos: the official SVGs listed in the season sheet\'s logos tab can be dropped in as `4k/teams/<name>.svg` once the team associations are confirmed (FUT, Weibo x FUT, NAVI, NAVI x Joel and the duplicate records stay untouched until then).']
open(os.path.join(ROOT, 'docs/4K-ASSET-REPORT.md'), 'w').write('\n'.join(L) + '\n')
print(f'{len(rows)} assets, {len(low)} limit 4K')
