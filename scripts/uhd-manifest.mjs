// Lists the 4K replacements in public/brand/overdrive/4k/ → shared/uhdAssets.generated.ts (run by `npm run build`).
import fs from 'node:fs';
import path from 'node:path';
const root = 'public/brand/overdrive/4k', out = 'shared/uhdAssets.generated.ts';
const map = {};
const walk = d => { if (!fs.existsSync(d)) return; for (const f of fs.readdirSync(d)) { const p = path.join(d, f); if (fs.statSync(p).isDirectory()) walk(p); else if (!/\.(md|txt)$/i.test(f)) { const rel = path.relative(root, p).split(path.sep).join('/'); map[rel.replace(/\.[^./]+$/, '')] = `/brand/overdrive/4k/${rel}`; } } };
walk(root);
const body = `// Generated by scripts/uhd-manifest.mjs from public/brand/overdrive/4k/. Do not edit.\n// Key = bundled asset path under /brand/overdrive/ without extension → its 4K replacement.\nexport const UHD_ASSETS: Record<string, string> = ${JSON.stringify(map, null, 1)};\n`;
if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== body) fs.writeFileSync(out, body);
console.log(`4K replacements: ${Object.keys(map).length}`);
