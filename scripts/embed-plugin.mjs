import fs from 'node:fs';
const dir = new URL('../plugin/BNLCamFollow/', import.meta.url);
const info = fs.readFileSync(new URL('info.toml', dir), 'utf8');
const main = fs.readFileSync(new URL('main.as', dir), 'utf8');
